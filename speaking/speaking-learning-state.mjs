const validId=id=>items.some(item=>item.id===id);
const validGroup=value=>value==='practice'||value==='remembered';
export function quizChoices(id){
 const current=items.find(item=>item.id===id);if(!current)return [];
 // Keep existing phrase distractors stable so saved attempts survive added vocabulary.
 const pool=items.filter(item=>item.lexicalKind===current.lexicalKind),index=pool.indexOf(current);
 return [pool[index],pool[(index+1)%pool.length],pool[(index+(pool.length>3?3:2))%pool.length]].sort((a,b)=>items.indexOf(a)-items.indexOf(b));
}
export function restoreState(raw){
 let value;try{value=typeof raw==='string'?JSON.parse(raw):raw;}catch{}value=value&&typeof value==='object'?value:{};
 const assessments=Object.fromEntries(Object.entries(value.assessments||{}).filter(([id,status])=>validId(id)&&validGroup(status)));
 const groups=Array.isArray(value.groups)?[...new Set(value.groups.filter(validGroup))]:['practice'];
 const selected=validId(value.selected)?value.selected:items[0].id;let quiz=null;
 if(value.quiz&&Array.isArray(value.quiz.ids)){
  const ids=[...new Set(value.quiz.ids.filter(validId))];
  if(ids.length){const answers=[];for(const answer of Array.isArray(value.quiz.answers)?value.quiz.answers:[]){if(answers.length>=ids.length||!quizChoices(ids[answers.length]).some(item=>item.id===answer))break;answers.push(answer);}
   const complete=value.quiz.complete===true&&answers.length===ids.length;
   const index=complete?ids.length-1:Math.min(Number.isInteger(value.quiz.index)?Math.max(0,value.quiz.index):0,answers.length,ids.length-1);
   quiz={ids,answers:answers.slice(0,complete?ids.length:index+1),index,complete};
  }
 }
 return {assessments,groups,selected,quiz};
}
export function readState(storage){try{return restoreState(storage.getItem(STORAGE_KEY));}catch{return restoreState();}}
export function saveState(storage,state){try{storage.setItem(STORAGE_KEY,JSON.stringify(state));}catch{}}
export function resetTopic(storage){
 try{storage.removeItem(STORAGE_KEY);storage.removeItem('wespark-speaking-hometown-learning-intro-v1');return true;}catch{return false;}
}
export function toggleAssessment(state,id,status){if(!validId(id)||!validGroup(status))return state;const assessments={...state.assessments};if(assessments[id]===status)delete assessments[id];else assessments[id]=status;return {...state,assessments};}
export function reviewIds(state){return items.filter(item=>state.groups.includes(state.assessments[item.id])).map(item=>item.id);}
export function startQuiz(state,ids=items.map(item=>item.id)){return {...state,quiz:{ids:[...new Set(ids.filter(validId))],answers:[],index:0,complete:false}};}
export function answerQuiz(state,id){const q=state.quiz;if(!q||q.complete||q.answers[q.index]||!quizChoices(q.ids[q.index]).some(item=>item.id===id))return state;return {...state,quiz:{...q,answers:[...q.answers,id]}};}
export function nextQuiz(state){const q=state.quiz;if(!q||q.complete||!q.answers[q.index])return state;return {...state,quiz:{...q,index:Math.min(q.index+1,q.ids.length-1),complete:q.index===q.ids.length-1}};}
